import asyncio
import os
import sys
from fastapi.testclient import TestClient

# Add backend directory to sys.path
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from app.main import app
from app.core.database import SessionLocal
from app.models.merchant import Merchant
from app.models.workflow import Workflow
from app.models.workflow_step import WorkflowStep
from app.core.security import create_access_token

def test_workflow_endpoints():
    client = TestClient(app)
    db = SessionLocal()
    
    # 1. Fetch our merchant
    merchant = db.query(Merchant).filter(Merchant.email == "merchant@reft.ai").first()
    if not merchant:
        merchant = db.query(Merchant).first()
    assert merchant is not None, "Merchant not found in DB"
    
    token = create_access_token(subject=str(merchant.id))
    headers = {"Authorization": f"Bearer {token}"}
    
    print(f"Testing with Merchant: {getattr(merchant, 'business_name', merchant.email)} (id={merchant.id})")
    
    # 2. Test AI Generation Endpoint
    print("\n--- 1. Testing POST /api/v1/workflows/generate-ai ---")
    gen_payload = {
        "order_id": "ORD-TEST-999",
        "product_name": "Bose QuietComfort 45 Headphones",
        "product_description": "Wireless noise cancelling over-ear headphones",
        "refund_reason": "Damaged on arrival",
        "refund_amount": 24990.0,
        "currency": "INR",
        "customer_name": "Rajesh Kumar",
        "claim_details": "Left earcup hinge physically cracked upon opening package, ANC not toggling.",
        "reference_profile_status": "Verified 4/4 Canonical Baseline Angles"
    }
    
    res = client.post("/api/v1/workflows/generate-ai", json=gen_payload, headers=headers)
    print(f"Status: {res.status_code}")
    assert res.status_code == 200, f"Generate AI failed: {res.text}"
    ai_data = res.json()
    print(f"Workflow Name: {ai_data.get('workflow_name')}")
    print(f"Claim Summary: {ai_data.get('claim_summary')}")
    print(f"Generated {len(ai_data.get('customer_questions', []))} questions:")
    for q in ai_data.get('customer_questions', []):
        print(f"  - [{q.get('question_type')}] {q.get('question')} (req={q.get('required')})")
    print(f"Verification steps: {ai_data.get('verification_steps')}")
    
    # 3. Test Save-Full Workflow Endpoint into SQLite
    print("\n--- 2. Testing POST /api/v1/workflows/save-full ---")
    save_payload = {
        "name": ai_data.get("workflow_name") or "Gemini Generated Test Flow",
        "description": ai_data.get("claim_summary") or "Test flow generated by Gemini AI",
        "layers": ai_data.get("enabled_verification_layers") or {
            "cameraFirst": True,
            "aiAuthenticity": True,
            "productReference": True
        },
        "questions": ai_data.get("customer_questions") or [],
        "conditional_follow_ups": ai_data.get("conditional_follow_ups") or [],
        "make_active": True
    }
    
    res_save = client.post("/api/v1/workflows/save-full", json=save_payload, headers=headers)
    print(f"Status: {res_save.status_code}")
    assert res_save.status_code == 200, f"Save-full failed: {res_save.text}"
    saved_wf = res_save.json()
    wf_id = saved_wf.get("id")
    print(f"Saved Workflow ID: {wf_id}")
    print(f"Is Active: {saved_wf.get('is_active')} / Status: {saved_wf.get('status')}")
    
    # 4. Verify in SQLite Database directly
    print("\n--- 3. Direct SQLite Database Inspection ---")
    db_wf = db.query(Workflow).filter(Workflow.id == wf_id).first()
    assert db_wf is not None, "Workflow not found in SQLite"
    print(f"DB Record: id={db_wf.id}, name='{db_wf.name}', is_active={db_wf.is_active}, merchant_id={db_wf.merchant_id}")
    
    # Verify steps
    steps = db.query(WorkflowStep).filter(WorkflowStep.workflow_id == wf_id).all()
    print(f"Persisted {len(steps)} workflow steps in DB:")
    for s in steps:
        print(f"  - Step: {s.title} (type={s.step_type}, order={s.step_order})")
    
    # 5. Verify Workflow retrieval through API
    print("\n--- 4. Testing GET /api/v1/workflows ---")
    res_list = client.get("/api/v1/workflows", headers=headers)
    assert res_list.status_code == 200
    wf_list = res_list.json()
    active_in_list = [w for w in wf_list if w.get("status") == "ACTIVE" or w.get("is_active")]
    print(f"Retrieved {len(wf_list)} total workflows, Active count: {len(active_in_list)}")
    matching = [w for w in wf_list if w["id"] == wf_id]
    assert len(matching) == 1, "Saved workflow not returned in GET /api/v1/workflows"
    assert matching[0].get("is_active") is True, "Saved workflow is not marked active in API response"
    print("SUCCESS: Workflow successfully created via Gemini AI, persisted into SQLite, and verified in API!")
    
    db.close()

if __name__ == "__main__":
    test_workflow_endpoints()
